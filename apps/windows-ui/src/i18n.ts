// Turkish is the primary UI language (the user is Turkish); English fills any
// key the Turkish table lacks.
export const lang: "tr" | "en" = "tr";
export const locale = lang === "tr" ? "tr-TR" : "en-US";

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = (lang === "tr" ? tr[key] : undefined) ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function platformName(p: string): string {
  return p === "windows" || p === "android" ? t(`platform.${p}`) : p;
}

export function relativeTime(ms: number): string {
  const diff = (ms - Date.now()) / 1000;
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "auto" });
  const abs = Math.abs(diff);
  if (abs < 60) return rtf.format(Math.round(diff), "second");
  if (abs < 3600) return rtf.format(Math.round(diff / 60), "minute");
  if (abs < 86400) return rtf.format(Math.round(diff / 3600), "hour");
  return rtf.format(Math.round(diff / 86400), "day");
}

/** A rough remaining time: seconds under a minute, then minutes, then hours. */
export function formatDuration(seconds: number): string {
  const s = Math.max(1, Math.round(seconds));
  if (s < 60) return t("duration.s", { n: s });
  if (s < 3600) return t("duration.m", { n: Math.round(s / 60) });
  return t("duration.h", { n: Math.floor(s / 3600), m: Math.round((s % 3600) / 60) });
}

export function formatSize(bytes: number): string {
  const units = ["B", "KB", "MB", "GB"];
  let v = bytes;
  let i = 0;
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024;
    i++;
  }
  return `${new Intl.NumberFormat(locale, { maximumFractionDigits: i === 0 ? 0 : 1 }).format(v)} ${units[i]}`;
}
